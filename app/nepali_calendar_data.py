"""Bikram Sambat month lengths — the DATA the conversion depends on.

Data only: no logic lives here, so the table can be diffed, checksummed and
re-verified on its own.

**Why a table and not a formula.** Bikram Sambat as used in Nepal is a sidereal
solar calendar: a month begins when the sun enters the next zodiac sign, so
month lengths vary between 29 and 32 days with no repeating cycle. There is
nothing to compute — every correct implementation is an anchor date plus a
table of month lengths, and conversion is day counting.

**Provenance.** Transcribed 2026-08-29 from `nepali-datetime` 1.0.8.5
(`nepali_datetime/data/calendar_bs.csv`, MIT), which itself follows Nepal's
Panchanga Nirnayak Samiti. 126 years, BS 1975-01-01 .. 2100-12-30, anchored at
BS 1975-01-01 = AD 1918-04-13, 46,022 days total.

**Published tables DISAGREE, and the disagreement is live — this is not a
far-edge curiosity.** Checked against a second implementation (`bikram`) over
32,873 days: the two agree exactly from 1944 to May 2025, then diverge by one
day from **AD 2025-05-14 onward, for the whole remaining range** — 1,176 days of
the sample. They disagree about the length of **Baisakh 2082**: 31 days here,
30 in `bikram`.

That was resolved against PRIMARY sources rather than by preferring a library:

  * hamropatro.com/date/2082-1-31 renders BS 2082 Baisakh 31 as Wed 14 May 2025
    — the date could not exist if the month had 30 days.
  * ADBL Bank published "Interest Rates Effective From Jestha 01, 2082
    (15 May, 2025)", which is Baisakh 1 (14 Apr 2025) + 31 days.

Both point the same way, so Baisakh 2082 has 31 days and this table is right
where `bikram` is wrong. Anyone revising these numbers needs evidence of that
kind — a second library agreeing is NOT evidence, since the disagreement above
is exactly two libraries disagreeing.

**Do not "fix" a year without a primary source.** A wrong month length does not
fail loudly: it shifts every subsequent date by a day, silently, forever after.
"""

